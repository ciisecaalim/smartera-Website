function course(
  partial: Omit<Course, "sections" | "previewVideo" | "certificateAvailable" | "language" | "totalLectures"> &
    Partial<Pick<Course, "previewVideo" | "certificateAvailable" | "language" | "sections" | "totalLectures">>,
): Course {
  const sections = partial.sections ?? buildCurriculum(partial.id, partial.skills.slice(0, 3));
  return {
    language: "English",
    certificateAvailable: true,
    previewVideo: DEMO_COURSE_VIDEO,
    ...partial,
    sections,
    totalLectures: sections.reduce((sum, section) => sum + section.lectures.length, 0),
  };
}

